--ctrg_support.key_to_id('part_supersession',CONCAT(KP.DUR_UK,'|',KP.DUR_UK,'|',KPN.DUR_UK)) as part_supersession_id,
      KP.DUR_UK_ID   AS PART_ID,
      KP.DUR_UK_ID   AS OLD_PART_ID,
      1 AS PART_SUPERSESSION_TYPE,
      CONCAT(KP.DUR_UK,'|',KP.DUR_UK,'|',KPN.DUR_UK) AS DUR_UK,
      (CASE WHEN PB.INTERCODE = '1' THEN 1::bool
            WHEN PB.INTERCODE = '2' THEN 0::bool  
		    ELSE 1::bool
        END)   AS FORWARD_ONLY,
       '0000000001'  AS SORT_SEQ,
       COALESCE(PSSD.DUR_UK_ID,DE.DUR_UK_ID) AS PART_SUPERSESSION_DICT_ID,
       NULL  AS PRICE_BOOK_ID,
       NULL::int  AS PART_SUPERSESSION_GROUP_ID,
       FALSE  AS OLD_PART_DISCON_BY_CONTEXT,
       FALSE  AS NEW_PART_DISCON_BY_CONTEXT,
       KP.DUR_UK  AS FLEX1,
       KP.DUR_UK  AS FLEX2,
       KPN.DUR_UK AS FLEX3,
       NULL       AS FLEX4,
       NULL       AS FLEX5,
       NULL       AS FLEX6,
       NULL       AS FLEX7,
       NULL       AS FLEX8,
       NULL       AS FLEX9,
       NULL       AS FLEX10,
       NULL       AS PART_SUPERSESSION_SET,
       NULL::timestamp with time zone  AS EFFECTIVE_DATE,
       NULL       AS QUANTITY,
       DOI.DATA_ORIGIN_ID  AS DATA_ORIGIN_ID,
       KPN.DUR_UK_ID       AS NEW_PART_ID,
       NULL::int           AS ROW_AE_ID,
       FALSE               AS ARCHIVABLE_IND,
       TRUE                AS VALID_FOR_MEDIA_IND,
       NULL                AS PART_SUPERSESSION_SET_OPERAND,
       DT.DISPLAY_TYPE_ID  AS DISPLAY_TYPE
  FROM DOI
  CROSS JOIN DT
  CROSS JOIN PB
  CROSS JOIN DEFAULT_ENTRY DE
  INNER JOIN CTRG_SUPPORT.PART_KEY_IDS KP
  ON PB.PART = KP.DUR_UK
  INNER JOIN CTRG_SUPPORT.PART_KEY_IDS KPN
  ON PB.NEWPART = KPN.DUR_UK
  LEFT OUTER JOIN PSD
  ON PB.PART = PSD.OLD_PART 
  AND PB.NEWPART = PSD.NEW_PART
  LEFT OUTER JOIN CTRG_SUPPORT.PART_SUPERSESSION_DICT_KEY_IDS PSSD
  ON PSD.ELEMENT_CODE = PSSD.DUR_UK;
